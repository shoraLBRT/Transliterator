namespace Transliterator.Tests.CorpusTests
{
    /// <summary>
    /// Места, где конвейер сегодня расходится с корпусом, и номер бага, который
    /// это чинит. Ожидание в корпусе — решение о системе записи, а не снимок
    /// вывода; пока баг открыт, вывод обязан отличаться, и отличаться ровно так,
    /// как здесь записано.
    /// <para>
    /// Реестр нужен, чтобы прогон корпуса был зелёным и при этом ничего не прятал.
    /// Красный прогон по восьми открытым багам сообщает ровно то, что и так
    /// написано в бэклоге, зато перестаёт сообщать про девятый: на фоне двадцати
    /// шести привычных падений новое не видно. Записанный вывод превращает
    /// «известно и заведено» в утверждение, которое проверяется: изменился вывод —
    /// прогон красный, сошёлся с ожиданием — тоже красный, с требованием убрать
    /// запись отсюда и снять чекбокс в бэклоге.
    /// </para>
    /// <para>
    /// Ключ — тот же идентификатор случая, что и в имени теста: <c>110:2</c> для
    /// текста в усмани, <c>110:2 имля</c> для современного написания того же аята.
    /// Запись удаляется тем же PR, который закрывает баг.
    /// </para>
    /// </summary>
    public static class KnownDivergences
    {
        /// <param name="Bug">Номера багов эпика B, из-за которых вывод такой.</param>
        /// <param name="Actual">Вывод конвейера на сегодня — целиком, а не отличающимся куском.</param>
        public sealed record Divergence(string Bug, string Actual);

        private static readonly Dictionary<string, Divergence> _entries = new()
        {
