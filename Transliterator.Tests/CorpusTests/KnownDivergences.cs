            ["1:7 имля"] = new("B5", "сIироотIо-ллязъиина ан'амта 'аляйhим гъойри-ль-могъдIууби 'аляйhим уаля-дIдIооооллииин"),
            ["109:1"] = new("B7", "qуль йаааъаййуhа-ль-каафирууун"),
            ["109:1 имля"] = new("B7", "qуль йаааъаййуhа-ль-каафирууун"),
            ["110:1"] = new("B5, B7", "изъаа джаааъа носIру-ллааhи уаль-фатхI"),
            ["110:1 имля"] = new("B5, B7, B8", "изъаа джаааъа носIру-ллааhи уаальфатхI"),
            ["110:2"] = new("B7", "уароъайта-ннааса йадхъулууна фии диини-лляяhи афуааджаа"),
            ["110:2 имля"] = new("B7", "уароъайта-ннааса йадхъулууна фии диини-лляяhи афуааджаа"),
            ["110:3"] = new("B5", "фасаббихI бихIамди роббика уастогъфирhу иннаhуу каана таууаабаа"),
            ["110:3 имля"] = new("B5, B8", "фасаббихI бихIамди роббика уаастогъфирhу иннаhуу каана таууаабаа"),
            ["111:2"] = new("B5, B6", "мааа огънааа 'анhу маалуhуу уамаа касаб"),
            ["111:3"] = new("B5, B6", "сайосIляаа наарон зъаата ляhаб"),
            ["111:4"] = new("B7", "уамроъатуhуу хIаммаалята-ль-хIатIоб"),
            ["111:4 имля"] = new("B7, B8", "уаамроъатуhуу хIаммаалята-ль-хIатIоб"),
            ["113:1"] = new("B5", "qуль а'уузъу биробби-ль-фалоq"),
            ["113:1 имля"] = new("B5", "qуль а'уузъу биробби-ль-фалоq"),
            ["113:2"] = new("B5", "мин щарри маа хъолоq"),
            ["114:6 имля"] = new("B8", "мина-ль-джиннати уааннааас"),
        };

        public static IReadOnlyDictionary<string, Divergence> Entries => _entries;

        public static bool TryGet(string caseId, out Divergence divergence) =>
            _entries.TryGetValue(caseId, out divergence!);

        /// <summary>
        /// Вывод, которого прогон ждёт от случая сегодня: ожидание корпуса, а у
        /// известного расхождения — записанный вывод. Из них же складывается
        /// ожидание посурового случая: сура — это её аяты подряд, и проверять
        /// в ней надо стыки, а не те же двадцать шесть багов ещё раз.
        /// </summary>
        public static string ExpectedToday(string caseId, string corpusExpected) =>
            _entries.TryGetValue(caseId, out var divergence) ? divergence.Actual : corpusExpected;
    }
}
