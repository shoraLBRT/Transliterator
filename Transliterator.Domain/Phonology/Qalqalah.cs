namespace Transliterator.Domain.Phonology
{
    /// <summary>
    /// Кальканя: призвук, которым размыкается безгласный взрывной ق ط ب ج د.
    /// Голосу нечем тянуть такой согласный, и смычка раскрывается коротким отзвуком.
    /// <para>
    /// Степеней две, и различает их не буква, а положение: посреди речи отзвук
    /// едва слышен (сугра), на остановке — отчётлив (кубра), потому что за ним
    /// уже ничего не следует и гасить его нечем.
    /// </para>
    /// </summary>
    public enum Qalqalah
    {
        None,

        /// <summary>Кальканя сугра: безгласная буква посреди слова или высказывания.</summary>
        Minor,

        /// <summary>Кальканя кубра: та же буква на паузе, отзвук усилен.</summary>
        Major
    }
}
