namespace Transliterator.Domain.Phonology
{
    /// <summary>
    /// Знак вакфа из коранической разметки. Это не приказ остановиться, а совет чтецу:
    /// каждый знак говорит, насколько остановка в этом месте уместна по смыслу.
    /// <para>
    /// Хранится отдельно от решения о паузе: сам знак — это то, что написано в мусхафе,
    /// а останавливается ли конвейер — политика стадии вакфа (<c>WaqfRule</c>).
    /// </para>
    /// </summary>
    public enum WaqfMark
    {
        /// <summary>Знака нет.</summary>
        None,

        /// <summary>ۖ (صلے) — соединение предпочтительнее остановки.</summary>
        ContinuePreferred,

        /// <summary>ۗ (قلے) — остановка предпочтительнее соединения.</summary>
        StopPreferred,

        /// <summary>ۘ (مـ) — обязательная остановка: без неё смысл искажается.</summary>
        Obligatory,

        /// <summary>ۙ (لا) — останавливаться нельзя.</summary>
        Forbidden,

        /// <summary>ۚ (ج) — остановка дозволена, но ничем не предпочтена.</summary>
        Permissible,

        /// <summary>ۛ (معانقة) — парный знак: останавливаться можно только в одном из двух мест.</summary>
        Embracing,

        /// <summary>ۜ (س) — сакта: мгновенная задержка голоса без разрыва дыхания.</summary>
        Saktah
    }
}
